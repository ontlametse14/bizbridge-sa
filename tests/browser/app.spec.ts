test('demo tabs serialize sales and a replay stays idempotent', async ({page,context})=>{
  await preview(page)
  const second=await context.newPage()
  await second.goto('/')
  await second.getByRole('button',{name:'Explore demo',exact:true}).click()
  await Promise.all([page.goto('/sales?new=1'),second.goto('/sales?new=1')])
  for(const p of [page,second])await p.getByLabel('Quantity',{exact:true}).fill('15')
  await Promise.all([page.getByRole('button',{name:'Record completed sale'}).click(),second.getByRole('button',{name:'Record completed sale'}).click()])
  const result=await page.evaluate(()=>JSON.parse(localStorage.getItem('bizbridge.demo.v1')!))
  expect(result.products[0].stock).toBe(3)
  expect(result.sales).toHaveLength(2)
  // Replay the exact persisted key through the same demo adapter. This tests
  // device storage behavior only, never claims database locking coverage.
  const retry=await page.evaluate(async()=>{
    const d=JSON.parse(localStorage.getItem('bizbridge.demo.v1')!),s=d.sales[0]
    const path='/src/demo.ts'
    const module=await import(/* @vite-ignore */path)
    await module.mutateDemo({kind:'sale',input:{product_id:s.product_id,quantity:s.quantity,sale_date:s.sale_date,payment_method:s.payment_method,idempotency_key:s.idempotency_key}})
    return JSON.parse(localStorage.getItem('bizbridge.demo.v1')!)
  })
  expect(retry.products[0].stock).toBe(3)
  expect(retry.sales).toHaveLength(2)
  await second.close()
})
