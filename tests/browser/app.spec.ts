import { test, expect, type Page } from '@playwright/test'
async function preview(page: Page) { await page.goto('/'); await page.getByRole('button',{name:'Explore demo',exact:true}).click(); await expect(page.getByRole('heading',{name:'A little clarity. A lot of possibility.'})).toBeVisible() }
test('sample acceptance values, navigation, persistence and safe exit', async ({page}, testInfo) => {
  const errors: string[]=[]; page.on('pageerror', e=>errors.push(e.message))
  await preview(page)
  for (const [label, amount] of [['Sales revenue','240'],['Cost of goods sold','140'],['Gross profit','100'],['Operating expenses','30'],['Estimated operating profit','70']]) await expect(page.locator('.stat-card').filter({has:page.locator('.stat-label').getByText(label,{exact:true})}).locator('.stat-value')).toContainText(amount)
  await expect(page.getByText('DEMO MODE', {exact:false}).first()).toBeVisible()
  await page.screenshot({path:`test-results/${testInfo.project.name}-dashboard.png`,fullPage:true})
  await page.goto('/products')
  await expect(page.getByRole('heading',{name:'Products & stock'})).toBeVisible()
  await page.getByRole('button',{name:'Add product',exact:true}).click()
  await page.getByLabel('Product name',{exact:true}).fill('Acceptance Cleaner')
  await page.getByLabel('Selling price (R)',{exact:true}).fill('120')
  await page.getByLabel('Unit cost (R, optional)',{exact:true}).fill('70')
  await page.getByLabel('Opening stock',{exact:true}).fill('20')
  await page.getByLabel('Low-stock threshold (optional)',{exact:true}).fill('5')
  await page.getByRole('dialog').getByRole('button',{name:'Add product',exact:true}).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.goto('/sales?new=1')
  await page.getByLabel('Product',{exact:true}).selectOption({label:'Acceptance Cleaner (20 available)'})
  await page.getByLabel('Quantity',{exact:true}).fill('2')
  await page.getByRole('button',{name:'Record completed sale'}).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.goto('/expenses?new=1')
  await page.getByLabel('Amount (R)',{exact:true}).fill('30')
  await page.getByRole('button',{name:'Record expense',exact:true}).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.goto('/products')
  await expect(page.locator('.product-row').filter({hasText:'Acceptance Cleaner'})).toContainText('18')
  await page.reload()
  await expect(page.getByRole('heading',{name:'Acceptance Cleaner',exact:true})).toBeVisible()
  await page.goto('/growth'); await expect(page.getByRole('heading',{name:'Your Growth Guide',exact:true})).toBeVisible()
  await page.getByRole('checkbox').nth(1).check()
  await expect(page.getByText('Your self-assessed checklist has been saved.')).toBeVisible()
  await page.reload(); await expect(page.getByRole('checkbox').nth(1)).toBeChecked()
  await page.screenshot({path:`test-results/${testInfo.project.name}-growth.png`,fullPage:true})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)
  if (testInfo.project.name==='mobile') await page.getByRole('button',{name:'Open navigation'}).click()
  await page.getByRole('button',{name:'Leave demo'}).click()
  await expect(page.getByRole('button',{name:'Explore demo',exact:true})).toBeVisible()
  await page.goto('/sales'); await expect(page.getByRole('heading',{name:'Sales',exact:true})).toHaveCount(0)
  expect(await page.evaluate(()=>Object.keys(sessionStorage).filter(k=>k.startsWith('bizbridge.pending.')).length)).toBe(0)
  expect(errors).toEqual([])
})
