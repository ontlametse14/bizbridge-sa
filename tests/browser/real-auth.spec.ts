import { test, expect } from '@playwright/test'
// Never retain authentication traffic or credential-bearing browser traces.
test.use({ trace: 'off', screenshot: 'off', video: 'off' })
test('real Supabase records survive reload; logout clears private screens', async ({page}) => {
  await page.goto('/')
  await expect(page.getByLabel('Email address',{exact:true})).toBeVisible()
  // Pass credentials as arguments to a trace-disabled evaluation, not action
  // labels or assertion payloads. Native setters notify React of the changes.
  await page.evaluate(({email,password}) => {
    const setter = Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value')!.set!
    for (const [name,value] of [['email',email],['password',password]]) {
      const input = document.querySelector<HTMLInputElement>(`input[name="${name}"]`)!
      setter.call(input,value); input.dispatchEvent(new Event('input',{bubbles:true}))
    }
  },{email:process.env.TEST_USER_A_EMAIL!,password:process.env.TEST_USER_A_PASSWORD!})
  await page.getByRole('button',{name:'Sign in',exact:true}).click()
  await expect(page.getByRole('heading',{name:'A little clarity. A lot of possibility.'})).toBeVisible()
  await page.goto('/sales')
  await expect(page.getByRole('heading',{name:'Sales history'})).toBeVisible()
  const records=await page.locator('.transaction').count()
  expect(records).toBeGreaterThan(0)
  const before=await page.locator('.transaction-list').textContent()
  await page.reload()
  await expect(page.getByRole('heading',{name:'Sales history'})).toBeVisible()
  await expect(page.locator('.transaction')).toHaveCount(records)
  expect(await page.locator('.transaction-list').textContent()).toBe(before)
  await page.goto('/money')
  await expect(page.getByTestId('money-cash')).toBeVisible()
  await expect(page.getByTestId('money-cash')).not.toHaveText('Not confirmed')
  const cashBefore=await page.getByTestId('money-cash').textContent()
  await page.reload(); await expect(page.getByTestId('money-cash')).toHaveText(cashBefore!)
  await page.getByRole('button',{name:'Help',exact:true}).click()
  await page.getByLabel('Ask a supported question').fill('business summary')
  await page.getByRole('button',{name:'Send question'}).click()
  await expect(page.locator('.helper-answer')).toContainText('Your authorised business records.')
  await expect(page.locator('.helper-answer')).not.toContainText('DEMO MODE')
  await page.getByRole('button',{name:'Close BizBridge Helper'}).click()
  const menu=page.getByRole('button',{name:'Open navigation'})
  if(await menu.isVisible())await menu.click()
  await page.getByRole('button',{name:'Log out',exact:true}).click()
  await expect(page.getByRole('button',{name:'Sign in',exact:true})).toBeVisible()
  // Check logout clearing immediately, before navigation or a page reload.
  await page.getByRole('button',{name:'Help',exact:true}).click()
  await expect(page.locator('.helper-turn')).toHaveCount(0)
  await page.getByLabel('Ask a supported question').fill('business summary')
  await page.getByRole('button',{name:'Send question'}).click()
  await expect(page.locator('.helper-answer')).toContainText('Sign in')
  await expect(page.locator('.helper-answer').locator('dd')).toHaveCount(0)
  await page.getByRole('button',{name:'Close BizBridge Helper'}).click()
  await page.goto('/sales')
  await expect(page.getByRole('button',{name:'Sign in',exact:true})).toBeVisible()
  await expect(page.locator('.transaction')).toHaveCount(0)
  expect(await page.evaluate(()=>localStorage.getItem('bizbridge.auth')===null)).toBe(true)
  expect(await page.evaluate(()=>Object.keys(sessionStorage).some(k=>k.startsWith('bizbridge.pending.')))).toBe(false)
  await page.getByRole('button',{name:'Help',exact:true}).click()
  await expect(page.locator('.helper-turn')).toHaveCount(0)
  await page.getByLabel('Ask a supported question').fill('business summary')
  await page.getByRole('button',{name:'Send question'}).click()
  await expect(page.locator('.helper-answer')).toContainText('Sign in')
  await expect(page.locator('.helper-answer').locator('dd')).toHaveCount(0)
  await page.goto('/money')
  await expect(page.getByRole('button',{name:'Sign in',exact:true})).toBeVisible()
  await expect(page.getByTestId('money-cash')).toHaveCount(0)
})
